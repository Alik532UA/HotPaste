/**
 * E2E над ЗІБРАНОЮ веб-оболонкою (BETA-CHECKLIST § 5.7, `BETA-PAGE-E2E`).
 *
 * ## Навіщо він тут зʼявився
 *
 * Над чеклистом стоять вісімнадцять інваріантів, і всі вони дивляться на ДАНІ
 * або на ДЖЕРЕЛА: чи заявлений екран вкладкою, чи існує названий файл тесту, чи
 * слухає застосунок названу клавішу. Між ними лишається діра розміром зі
 * сторінку — чи взагалі працює те, заради чого все це написано: позначка, що
 * переживає перезавантаження, поступ, який росте, і звіт, який доходить до
 * людини, коли буфер обміну відмовив.
 *
 * ## Чому `preview`, а не `dev`
 *
 * Dev і збірка — різні застосунки саме там, де живуть найдорожчі дефекти:
 * політика безпеки в dev приходить інакше, а хеші інлайн-скриптів рахуються зі
 * ЗБІРКИ. Сторінка, яка працює в dev і мовчки блокується політикою у зібраному
 * вигляді, — це рівно те, що цей прогін мусить ловити.
 *
 * ## Чому лише chromium
 *
 * Обидві оболонки застосунку показують вміст у WebView на Chromium: віконна —
 * через WebView2, веб — у браузері користувача. Прогін у Firefox і WebKit
 * перевіряв би двигуни, під якими застосунок не працює ні в кого.
 */
