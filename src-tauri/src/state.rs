//! СПІЛЬНИЙ СТАН — те, що переживає модулі.
//!
//! Тут лежать рівно чотири речі, і всі вони спільні НЕ з ліні, а тому що
//! описують одну машину: дескриптор застосунку, прапорець мінімального
//! режиму, дочірній процес гака й прапорець «не показувати вікно консолі».
//!
//! Винесено в окремий модуль, бо інакше кожен із шести модулів мусив би
//! тягнути їх із `crate::` кореня — а корінь після поділу тримає лише `run()`,
//! і складати в нього стан означало б повернути той самий моноліт, тільки
//! коротший.
use std::sync::atomic::AtomicBool;
use std::sync::OnceLock;
use tauri::AppHandle;

/// Прапорець для `Command`: не блимати вікном консолі на кожен PowerShell.
#[cfg(target_os = "windows")]
pub(crate) const CREATE_NO_WINDOW: u32 = 0x08000000;

/// Дескриптор застосунку для потоку, який читає `stdout` гака.
///
/// `OnceLock`, а не `Mutex`: пишеться один раз у `setup`, далі лише читається.
pub(crate) static APP_HANDLE: OnceLock<AppHandle> = OnceLock::new();

/// Чи вікно зараз у мінімальному режимі. Переживає сховування вікна.
pub(crate) static IS_MINIMAL: AtomicBool = AtomicBool::new(false);

/// Дочірній процес гака клавіатури.
///
/// Тримається саме тут, а не в `hook.rs`, бо вбиває його ще й `run()` — на
/// закритті вікна й на виході з трея. Процес, який пережив застосунок,
/// лишається в системі з живим низькорівневим гаком: наступний запуск
/// отримує двох слухачів на одну клавішу.
pub(crate) static HOOK_CHILD: std::sync::Mutex<Option<std::process::Child>> =
    std::sync::Mutex::new(None);
