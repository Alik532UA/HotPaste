/**
 * КОЛИ ПИТАТИ СЕРВЕР, ЧИ Є НОВА ВЕРСІЯ.
 *
 * ## Чому це окремий модуль, а не десяток рядків у компоненті
 *
 * Доти цей розклад жив усередині `ReloadPrompt.svelte` — три змінні, таймер і
 * два слухачі поруч із розміткою. Працював він правильно, і саме тому питання
 * не в охайності: **перевірити його там було неможливо**. Логіка сиділа в
 * замиканні всередині `onRegisteredSW`, тобто дістатися до неї можна було
 * тільки змонтувавши компонент, зареєструвавши справжній service worker і
 * посунувши час. Отже вона не перевірялася ніяк.
 *
 * А правило тут неочевидне рівно настільки, щоб його зламали при наступній
 * правці, і зламали ТИХО: пропозиція оновитися просто перестала б з'являтися,
 * і дізнатися про це не було б звідки.
 *
 * ## Чому не просто `setInterval`
 *
 * Бо крім таймера є повернення до вкладки, і воно важливіше: HotPaste тримають
 * відкритим годинами й не перезавантажують, а браузер сам перевіряє воркер
 * лише на НАВІГАЦІЇ. Без цього нова версія чекала б до наступного відкриття.
 *
 * Але повернення піднімає ДВІ події — `visibilitychange` і `focus`, — тож без
 * спільного проміжку одне переключення вікна дає два запити поспіль.
 *
 * ## Той самий модуль стоїть у сусідньому AudioRemote
 *
 * Там він з'явився першим і з тієї ж причини. Спільної бібліотеки між
 * проєктами немає (і заводити її заради тридцяти рядків не варто), тож це
 * свідома копія — але копія з тестами по обидва боки, а не мовчазна.
 */

/** Як часто питати, поки вікно не чіпають. */
export const CHECK_EVERY_MS = 30 * 60 * 1000;

/**
 * Найменший проміжок між двома запитами.
 *
 * Не оптимізація: без нього повернення до вікна б'є двома запитами підряд, бо
 * `visibilitychange` і `focus` приходять обидва.
 */
export const MIN_GAP_MS = 60 * 1000;

export interface UpdateHost {
	now(): number;
	/** Офлайн — не привід питати: відповіді все одно не буде. */
	online(): boolean;
	/** Власне запит до сервера: у житті це `registration.update()`. */
	update(): void;
}

export interface UpdateSchedule {
	/** Спробувати спитати. Повертає, чи справді пішли. */
	tick(): boolean;
}

export function createUpdateSchedule(host: UpdateHost): UpdateSchedule {
	/*
	 * `null`, а НЕ `0`, і це не смак.
	 *
	 * Тут стояло `let lastAt = 0` з умовою `lastAt !== 0 && …`, тобто нуль
	 * означав «ще не питали». Але нуль — це ще й дійсна мітка часу, тож якщо
	 * перший запит випадав рівно на неї, наступний тік не бачив проміжку й
	 * ішов одразу — саме той подвійний запит, проти якого проміжок і стоїть.
	 *
	 * У житті `Date.now()` нуля не віддає, тож вада латентна. Але вона робить
	 * функцію неправдивою для частини входів, а перевірка, підігнана під
	 * «беріть час не з нуля», перевіряла б не правило, а зручний випадок.
	 */
	let lastAt: number | null = null;

	return {
		tick() {
			if (!host.online()) return false;

			const now = host.now();
			if (lastAt !== null && now - lastAt < MIN_GAP_MS) return false;

			lastAt = now;
			host.update();
			return true;
		}
	};
}
