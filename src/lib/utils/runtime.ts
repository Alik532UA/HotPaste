/**
 * Де ми виконуємося: у вікні застосунку чи у вкладці браузера.
 *
 * ## Чому окремий модуль, а не вираз на місці
 *
 * Цей самий вираз був переписаний У ДЕСЯТИ місцях, і вже в трьох формах:
 * `!!(a || b)`, `(!!a || !!b)`, `typeof window !== 'undefined' && (a || b)`.
 * Копія, переписана від руки, розходиться — і розійшлася: `index.html`
 * перевіряв ЛИШЕ `window.__TAURI__`, а решта дивилася ще й на
 * `__TAURI_INTERNALS__`.
 *
 * ## Чому саме `__TAURI_INTERNALS__`
 *
 * `window.__TAURI__` — це глобальний JS API, і він існує тільки тоді, коли
 * ввімкнено `withGlobalTauri`. Прапорець прибрано: він віддає сторінці весь
 * API одним об'єктом, тобто будь-який сторонній скрипт у вебв'ю дістає його
 * без жодного імпорту. Модулі `@tauri-apps/api` працюють і без нього — вони
 * ходять через `__TAURI_INTERNALS__`, який є завжди.
 *
 * Отже перевірка `!!window.__TAURI__` після цього стала б назавжди хибною —
 * саме тому вона тут і не лишилася. `__TAURI__` згадується нижче рівно один
 * раз: щоб старі збірки, у яких прапорець ще був, теж розпізнавалися.
 *
 * Інваріант тримає `src/runtime.test.ts`: цього виразу не має бути більше
 * ніде, включно з `index.html`.
 */

interface TauriWindow {
	__TAURI_INTERNALS__?: unknown;
	__TAURI__?: unknown;
}

/** `true` у вікні застосунку, `false` у браузері та під час тестів у node. */
export function isTauri(): boolean {
	if (typeof window === 'undefined') return false;
	const w = window as unknown as TauriWindow;
	return !!w.__TAURI_INTERNALS__ || !!w.__TAURI__;
}
